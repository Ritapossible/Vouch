# Module level rather than methods: they run inside nondet blocks, where `self`
# carries storage handles that are unusable.


def _leader_payload(leader_res: object) -> dict | None:
    """The leader's attestation, unwrapped. `None` means unusable.

    `run_nondet_unsafe` hands the validator function a `gl.vm.Result`, and the
    value `compute` returned is behind `.calldata`. A validator that compares
    against the wrapper instead of its contents rejects every leader, including
    an honest one -- and does it quietly, since each node's own execution
    succeeds and only the vote comes back wrong.

    Split out and named so it can be tested directly. The bug it exists to
    prevent is invisible to every local check: the contract runs, the leader
    produces a correct answer, and the transaction still ends UNDETERMINED.
    """
    if not isinstance(leader_res, gl.vm.Return):
        return None
    payload = leader_res.calldata
    if isinstance(payload, str):
        try:
            payload = json.loads(payload)
        except (json.JSONDecodeError, TypeError, ValueError):
            return None
    return payload if isinstance(payload, dict) else None


def _listed_attestation(pairs: tuple, result: str) -> dict:
    """The attestation an allow/denylist hit produces, with no network at all.

    Every claim takes the list's result and is marked `deterministic`, because
    that is what it is: an operator's assertion, not a judgment.
    """
    claims = []
    for key, _ in pairs:
        claims.append(
            {
                "key": key,
                "result": result,
                "method": METHOD_DETERMINISTIC,
                "confidence": 100,
            }
        )
    return {
        "verdict": aggregate([c["result"] for c in claims]),
        "claims": claims,
        "resolved_by": BY_LIST,
        "sources_reachable": 0,
    }


def _fetch(url: str, max_bytes: int) -> tuple:
    """Fetch and flatten one source. `None` text means unreachable.

    Unreachable is never fatal and never `contradicted`: a dead link is a fact
    about the network, so the check proceeds on whatever else was reachable and
    the claim it would have settled stays `unsubstantiated`.

    Fetched with `render(mode="html")` rather than `get()`. Rendered HTML
    carries both post-JavaScript content and attribute values, and a payment
    address lives in an `href` about as often as in body text.
    """
    raw = None
    try:
        raw = gl.nondet.web.render(url, mode="html", wait_after_loaded="1000ms")
    except Exception:
        raw = None
    if raw is None:
        # A node without WebRender support falls back rather than reporting the
        # vendor unreachable. The fallback loses JavaScript-rendered content and
        # can only cost a substantiation, never manufacture one.
        try:
            res = gl.nondet.web.get(url)
            status = getattr(res, "status", 0)
            if isinstance(status, int) and 200 <= status < 300:
                body = getattr(res, "body", None)
                if isinstance(body, bytes):
                    raw = body.decode("utf-8", errors="replace")
                elif body is not None:
                    raw = str(body)
        except Exception:
            raw = None
    if not isinstance(raw, str) or not raw:
        return (None, False)

    text = normalize(html_to_text(raw))
    text, cut = truncate(text, max_bytes)
    return (text, cut)


def _gather(urls: list, max_bytes: int) -> list:
    """Fetch every source. One entry per URL, reachable or not."""
    out = []
    for url in urls:
        text, cut = _fetch(url, max_bytes)
        out.append({"url": url, "text": text, "truncated": cut})
    return out


def _derive(gathered: list, pairs: tuple, target: str, model_pairs: tuple, min_conf: int) -> dict:
    """Settle every claim. Deterministic ones first, model only if needed.

    Runs identically in the leader and in every validator -- it is the whole
    computation, which is what makes re-running it a real check rather than a
    review of the leader's homework.
    """
    reachable = [g for g in gathered if g["text"]]
    joined = " ".join(g["text"] for g in reachable)

    foreign = foreign_addresses(joined, target) if joined else ()
    address_hit = address_present(target, joined) if joined else False

    results = {}
    for key, value in pairs:
        if key == CLAIM_PAYMENT_ADDRESS:
            if address_hit:
                results[key] = (SUBSTANTIATED, METHOD_DETERMINISTIC, 100)
            elif foreign:
                # The page is up and names a different payment address. This is
                # positive evidence of conflict, not an absence of evidence, and
                # it is the case worth separating from silence.
                results[key] = (CONTRADICTED, METHOD_DETERMINISTIC, 100)
            else:
                results[key] = (UNSUBSTANTIATED, METHOD_DETERMINISTIC, 0)
        elif key == CLAIM_DOMAIN:
            want = registrable(host_of("https://" + value.strip().lower().lstrip("htps:/")))
            if not want:
                want = registrable(value)
            hit = False
            mismatch = False
            for g in reachable:
                got = registrable(host_of(g["url"]))
                if got and want and got == want:
                    hit = True
                elif got and want:
                    mismatch = True
            if hit:
                results[key] = (SUBSTANTIATED, METHOD_DETERMINISTIC, 100)
            elif mismatch:
                results[key] = (CONTRADICTED, METHOD_DETERMINISTIC, 100)
            else:
                results[key] = (UNSUBSTANTIATED, METHOD_DETERMINISTIC, 0)
        elif key == CLAIM_REGISTRY_ID:
            needle = normalize(value)
            if needle and joined and needle in joined:
                results[key] = (SUBSTANTIATED, METHOD_DETERMINISTIC, 100)
            else:
                results[key] = (UNSUBSTANTIATED, METHOD_DETERMINISTIC, 0)
        else:
            results[key] = (UNSUBSTANTIATED, METHOD_MODEL, 0)

    quotes = []
    # Stage 3 runs only when there is a fuzzy claim left and something to read.
    # No reachable source means no prompt: asking a model to judge a claim
    # against nothing is paying for a guess.
    if model_pairs and reachable:
        answer = None
        try:
            prompt = build_prompt(
                model_pairs, [(g["url"], g["text"]) for g in reachable]
            )
            answer = gl.nondet.exec_prompt(prompt, response_format="json")
        except Exception:
            answer = None
        if isinstance(answer, str):
            try:
                answer = json.loads(answer)
            except (json.JSONDecodeError, TypeError, ValueError):
                answer = None
        if isinstance(answer, dict):
            entries = answer.get("claims")
            if isinstance(entries, list):
                allowed = {k for k, _ in model_pairs}
                for item in entries:
                    if not isinstance(item, dict):
                        continue
                    ckey = item.get("key")
                    if not isinstance(ckey, str) or ckey not in allowed:
                        continue
                    result, conf = coerce_model_result(
                        item.get("result"), item.get("confidence", 0), min_conf
                    )
                    results[ckey] = (result, METHOD_MODEL, conf)
                    quote = item.get("quote")
                    if isinstance(quote, str) and quote.strip():
                        quotes.append(
                            {
                                "claim": ckey,
                                "text": quote[:MAX_QUOTE_LEN],
                            }
                        )

    claims = []
    for key, _ in pairs:
        result, method, conf = results.get(key, (UNSUBSTANTIATED, METHOD_MODEL, 0))
        claims.append(
            {"key": key, "result": result, "method": method, "confidence": conf}
        )

    return {
        "verdict": aggregate([c["result"] for c in claims]),
        "claims": claims,
        "resolved_by": BY_MODEL if model_pairs and reachable else BY_DETERMINISTIC,
        "sources_reachable": len(reachable),
        # Leader-observed, never consensus-verified. Validators fetch different
        # bytes and quote different passages, so none of this is compared and
        # none of it carries a guarantee. Recorded because a human reviewing a
        # refusal wants it; segregated because an audit aid presented as a
        # guarantee is a liability.
        "observed": {
            "quotes": quotes,
            "source_digests": [digest(g["text"] or "") for g in gathered],
            "foreign_addresses": list(foreign),
            "truncated": [bool(g["truncated"]) for g in gathered],
        },
    }


def parse_block_time(raw: object) -> int:
    """Block time as a Unix timestamp.

    `calendar.timegm` on the UTC struct rather than `.timestamp()`, because the
    latter interprets a naive datetime in the validator's local zone and every
    validator would then disagree about what time it is.
    """
    if isinstance(raw, (int, float)):
        value = int(raw)
        if value < 0 or value > U256_MAX:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bad block time: out of range")
        return value
    if not isinstance(raw, str):
        raise gl.vm.UserError(f"{ERROR_EXPECTED} bad block time: not a string")
    text = raw.strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError:
        raise gl.vm.UserError(f"{ERROR_EXPECTED} bad block time: unparseable") from None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    value = int(parsed.astimezone(timezone.utc).timestamp())
    if value < 0 or value > U256_MAX:
        raise gl.vm.UserError(f"{ERROR_EXPECTED} bad block time: out of range")
    return value
