"""Vouch -- pre-payment counterparty substantiation.

An agent cannot pay a counterparty that does not demonstrably exist. `check`
runs four stages, cheapest first, and records an attestation that settlement can
be made to require.

    stage 0  cache          prior attestation within TTL      no network, no model
    stage 1  screen         addresses, lists, URL validation   no network, no model
    stage 2  corroborate    does the address appear on-site?   network, no model
    stage 3  substantiate   the fuzzy claims only              network and model

Most calls stop at 0 or 1. The stage that catches the most fraud is stage 2, and
it uses no model at all: a substring search for the payment address in the
vendor's own published page defeats invoice redirection outright.

Three values, never two. `unsubstantiated` means the evidence does not support
the claim; `contradicted` means the evidence positively conflicts with it. An
unreachable site is the former. A site naming a different payment address is the
latter, and the difference is the whole point -- "we could not check" and "we
checked and it is wrong" call for opposite responses.

The invariant, stated as an absence, because that is the only useful way to
state a safety property:

    **No error path produces `substantiated`.**

Every failure resolves toward `unsubstantiated`. A model can never reach
`contradicted`. A leader cannot assert a verdict; the verdict is derived from
the claims by fixed rule in code every validator runs.

This file is GENERATED. `lib/vouch_core.py`, `lib/vouch_evidence.py` and
`lib/vouch_prompts.py` are the source of truth; everything between the INLINE
markers is machine-managed. Run `python tools/build_contract.py` after any
change to them. The split exists because `genlayer deploy --contract` reads one
path and does no module bundling, so a local `import vouch_core` resolves on a
dev box and finds nothing on-chain.
"""

