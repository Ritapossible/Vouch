LIST_ALLOW = "allow"
LIST_DENY = "deny"
LIST_NONE = "none"

MAX_OBSERVED_LEN = 8000


@allow_storage
@dataclass
class ClaimRow:
    key: str
    result: str
    method: str
    confidence: u256


@allow_storage
@dataclass
class Attestation:
    payee: str
    verdict: str
    resolved_by: str
    sources_reachable: u256
    checked_at: u256
    claims: DynArray[ClaimRow]
    observed: str


class Vouch(gl.Contract):
    owner: Address

    max_sources: u256
    max_source_bytes: u256
    min_confidence: u256
    confidence_tol: u256
    cache_ttl: u256

    count: u256
    attestations: TreeMap[str, Attestation]
    listing: TreeMap[str, str]

    def __init__(
        self,
        max_sources: int = 3,
        max_source_bytes: int = 200000,
        min_confidence: int = 75,
        confidence_tol: int = 15,
        cache_ttl: int = 86400,
    ):
        limits = Limits(
            max_sources, max_source_bytes, min_confidence, confidence_tol, cache_ttl
        )
        bad = validate_limits(limits)
        if bad:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} {bad}")

        self.owner = gl.message.sender_address
        self.max_sources = u256(limits.max_sources)
        self.max_source_bytes = u256(limits.max_source_bytes)
        self.min_confidence = u256(limits.min_confidence)
        self.confidence_tol = u256(limits.confidence_tol)
        self.cache_ttl = u256(limits.cache_ttl)
        self.count = u256(0)

    # --- internals --------------------------------------------------------

    def _limits(self) -> "Limits":
        return Limits(
            int(self.max_sources),
            int(self.max_source_bytes),
            int(self.min_confidence),
            int(self.confidence_tol),
            int(self.cache_ttl),
        )

    def _now(self) -> int:
        """Block time. Never wall clock.

        Wall clock differs per validator, and a TTL comparison against it would
        make every cache read a source of disagreement.
        """
        try:
            raw = gl.message_raw["datetime"]
        except (KeyError, TypeError) as e:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} bad block time: {e}") from None
        return parse_block_time(raw)

    def _key(self, payee: str, claims: dict) -> tuple:
        """`(canonical payee, claim pairs, cache key)`, or a raise."""
        canon = canonical_address(payee)
        if not canon:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} {REASON_BAD_PAYEE}")
        pairs, err = canonical_claims(claims)
        if err:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} {err}")
        return (canon, pairs, cache_key(canon, pairs))

    def _read(self, key: str) -> dict | None:
        record = self.attestations.get(key)
        if record is None:
            return None
        claims = []
        for row in record.claims:
            claims.append(
                {
                    "key": str(row.key),
                    "result": str(row.result),
                    "method": str(row.method),
                    "confidence": int(row.confidence),
                }
            )
        observed = str(record.observed)
        try:
            parsed = json.loads(observed) if observed else {}
        except (json.JSONDecodeError, TypeError, ValueError):
            parsed = {}
        return {
            "payee": str(record.payee),
            "verdict": str(record.verdict),
            "claims": claims,
            "resolved_by": str(record.resolved_by),
            "sources_reachable": int(record.sources_reachable),
            "checked_at": int(record.checked_at),
            "observed": parsed,
        }

    def _write(self, key: str, payee: str, canon: dict, observed: dict, now: int) -> dict:
        # A plain list, never `DynArray[ClaimRow]()`. The SDK converts a list
        # on assignment to a `DynArray` field; constructing one directly in
        # memory escapes as an unclassified VM fault -- `exit_code 1` with no
        # stderr, which is the same shape of failure MandateVault records for
        # `gl.storage.copy_to_memory`. It costs a deployment to learn each time.
        rows = [
            ClaimRow(
                key=str(entry["key"]),
                result=str(entry["result"]),
                method=str(entry["method"]),
                confidence=u256(int(entry["confidence"])),
            )
            for entry in canon["claims"]
        ]
        blob = ""
        try:
            blob = json.dumps(observed)[:MAX_OBSERVED_LEN]
        except (TypeError, ValueError):
            blob = ""

        existed = self.attestations.get(key) is not None
        self.attestations[key] = Attestation(
            payee=payee,
            verdict=str(canon["verdict"]),
            resolved_by=str(canon["resolved_by"]),
            sources_reachable=u256(int(canon["sources_reachable"])),
            checked_at=u256(int(now)),
            claims=rows,
            observed=blob,
        )
        if not existed:
            self.count = u256(int(self.count) + 1)

        out = dict(canon)
        out["payee"] = payee
        out["checked_at"] = int(now)
        out["observed"] = observed
        return out

    # --- views ------------------------------------------------------------

    @gl.public.view
    def total(self) -> int:
        return int(self.count)

    @gl.public.view
    def limits(self) -> dict:
        return {
            "max_sources": int(self.max_sources),
            "max_source_bytes": int(self.max_source_bytes),
            "min_confidence": int(self.min_confidence),
            "confidence_tol": int(self.confidence_tol),
            "cache_ttl": int(self.cache_ttl),
        }

    @gl.public.view
    def listed(self, payee: str) -> str:
        canon = canonical_address(payee)
        if not canon:
            return LIST_NONE
        value = self.listing.get(canon)
        return str(value) if value else LIST_NONE

    @gl.public.view
    def attestation(self, payee: str, claims: dict) -> dict | None:
        """The cached attestation, or `None`. Never triggers a check.

        Free and side-effect free, so a UI can call it on every keystroke to
        show current status without committing to a verification.
        """
        _, _, key = self._key(payee, claims)
        return self._read(key)

    @gl.public.view
    def is_current(self, payee: str, claims: dict) -> bool:
        """Whether a cached attestation exists and is within TTL."""
        _, _, key = self._key(payee, claims)
        record = self._read(key)
        if record is None:
            return False
        return not self._stale(record)

    def _stale(self, record: dict) -> bool:
        ttl = int(self.cache_ttl)
        if ttl <= 0:
            return True
        try:
            now = self._now()
        except Exception:
            return True
        return now - int(record["checked_at"]) >= ttl

    # --- lists ------------------------------------------------------------

    def _require_owner(self) -> None:
        if gl.message.sender_address != self.owner:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} {REASON_NOT_OWNER}")

    @gl.public.write
    def set_denylist(self, payee: str, value: bool) -> dict:
        return self._set_list(payee, value, LIST_DENY)

    @gl.public.write
    def set_allowlist(self, payee: str, value: bool) -> dict:
        return self._set_list(payee, value, LIST_ALLOW)

    def _set_list(self, payee: str, value: object, which: str) -> dict:
        self._require_owner()
        if not isinstance(value, bool):
            raise gl.vm.UserError(f"{ERROR_EXPECTED} value must be a boolean")
        canon = canonical_address(payee)
        if not canon:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} {REASON_BAD_PAYEE}")
        if value:
            self.listing[canon] = which
        else:
            current = self.listing.get(canon)
            if current is not None and str(current) == which:
                self.listing[canon] = ""
        return {"payee": canon, "listed": self.listed(canon)}

    # --- the main call ----------------------------------------------------

    @gl.public.write
    def check(self, payee: str, claims: dict, sources: list) -> dict:
        """Substantiate a counterparty. Stages 0-3, cheapest first."""
        limits = self._limits()
        canon_payee, pairs, key = self._key(payee, claims)
        now = self._now()

        # --- stage 0: cache -----------------------------------------------
        cached = self._read(key)
        if cached is not None and not self._stale(cached):
            out = dict(cached)
            out["resolved_by"] = BY_CACHE
            return out

        # --- stage 1: screen ----------------------------------------------
        listing = self.listed(canon_payee)
        if listing == LIST_DENY:
            canon = _listed_attestation(pairs, CONTRADICTED)
            return self._write(key, canon_payee, canon, {"listed": LIST_DENY}, now)
        if listing == LIST_ALLOW:
            canon = _listed_attestation(pairs, SUBSTANTIATED)
            return self._write(key, canon_payee, canon, {"listed": LIST_ALLOW}, now)

        if not isinstance(sources, list) or not sources:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} {REASON_NO_SOURCES}")
        if len(sources) > limits.max_sources:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} {REASON_TOO_MANY_SOURCES}")
        urls = []
        for raw in sources:
            reason = validate_url(raw)
            if reason:
                raise gl.vm.UserError(f"{ERROR_EXPECTED} {REASON_BAD_URL}: {reason}")
            urls.append(str(raw).strip())

        # The address the deterministic check looks for: the `payment_address`
        # claim if the caller made one, otherwise the payee itself. A caller who
        # names no address is still asking "is this the address to pay?".
        target = canon_payee
        for ckey, cvalue in pairs:
            if ckey == CLAIM_PAYMENT_ADDRESS:
                named = canonical_address(cvalue)
                # A malformed `payment_address` claim cannot be substantiated by
                # a search for something else, so it is rejected rather than
                # silently falling back to the payee.
                if not named:
                    raise gl.vm.UserError(f"{ERROR_EXPECTED} {REASON_BAD_CLAIMS}")
                target = named

        expected_keys = tuple(k for k, _ in pairs)
        model_pairs = tuple((k, v) for k, v in pairs if k in MODEL_CLAIMS)
        min_conf = limits.min_confidence
        tol = limits.confidence_tol
        max_bytes = limits.max_source_bytes

        # --- stages 2 and 3: one nondet block -----------------------------
        #
        # One block, not two. A gather round followed by a ruling round would
        # have to either re-fetch every source or carry the leader's observation
        # into a consensus input, and the second is what CONSENSUS.md forbids.
        def compute() -> str:
            gathered = _gather(urls, max_bytes)
            derived = _derive(gathered, pairs, target, model_pairs, min_conf)
            return json.dumps(derived)

        def validator_fn(leader_res: gl.vm.Result) -> bool:
            """Re-run everything and compare. Never trust the leader's answer.

            The validator fetches its own pages, runs its own substring checks
            and asks its own model. What it compares is the derived verdict, not
            the bytes -- validators legitimately fetch different bytes from the
            same URL, and requiring byte equality would make every check fail.

            The argument is a `gl.vm.Result`, **not** the value `compute`
            returned; the leader's payload is behind `.calldata`. Treating it as
            the value directly type-checks, runs, and makes every validator
            disagree with a leader that did nothing wrong -- silently, because
            each node's own execution still succeeds.
            """
            theirs_raw = _leader_payload(leader_res)
            if theirs_raw is None:
                return False
            theirs = canonicalize_attestation(theirs_raw, expected_keys, min_conf)

            gathered = _gather(urls, max_bytes)
            mine_raw = _derive(gathered, pairs, target, model_pairs, min_conf)
            mine = canonicalize_attestation(mine_raw, expected_keys, min_conf)
            return verdicts_agree(mine, theirs, tol)

        raw = gl.vm.run_nondet_unsafe(compute, validator_fn)
        payload = raw
        if isinstance(payload, str):
            try:
                payload = json.loads(payload)
            except (json.JSONDecodeError, TypeError, ValueError):
                payload = None

        canon = canonicalize_attestation(payload, expected_keys, min_conf)
        observed = {}
        if isinstance(payload, dict) and isinstance(payload.get("observed"), dict):
            observed = payload["observed"]
        return self._write(key, canon_payee, canon, observed, now)


# --- nondet helpers -------------------------------------------------------
